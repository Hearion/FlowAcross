pub fn from_mac(vk: u16) -> Option<KeyCode> {
    TABLE
        .iter()
        .find(|e| e.1 == vk && vk != NONE)
        .map(|e| KeyCode(e.0))
}

pub fn to_mac(code: KeyCode) -> Option<u16> {
    TABLE
        .iter()
        .find(|e| e.0 == code.0 && e.1 != NONE)
        .map(|e| e.1)
}

/// `scan` 为钩子报告的扫描码，`extended` 为扩展键标记（E0 前缀）。
pub fn from_win(scan: u16, extended: bool) -> Option<KeyCode> {
    let key = if extended { 0xE000 | scan } else { scan };
    TABLE
        .iter()
        .find(|e| e.2 == key && key != NONE)
        .map(|e| KeyCode(e.0))
}

/// 返回 (扫描码, 是否扩展键)。
pub fn to_win(code: KeyCode) -> Option<(u16, bool)> {
    TABLE
        .iter()
        .find(|e| e.0 == code.0 && e.2 != NONE)
        .map(|e| (e.2 & 0xFF, e.2 & 0xE000 == 0xE000))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn no_duplicates() {
        let mut hid = HashSet::new();
        let mut mac = HashSet::new();
        let mut win = HashSet::new();
        for &(h, m, w) in TABLE {
            assert!(hid.insert(h), "HID 重复：{h:#x}");
            if m != NONE {
                assert!(mac.insert(m), "macOS 键码重复：{m:#x}");
            }
            if w != NONE {
                assert!(win.insert(w), "Windows 扫描码重复：{w:#x}");
            }
        }
    }

    #[test]
    fn round_trips() {
        for &(h, m, w) in TABLE {
            let code = KeyCode(h);
            if m != NONE {
                assert_eq!(from_mac(m), Some(code));
                assert_eq!(to_mac(code), Some(m));
            }
            if w != NONE {
                let (scan, ext) = to_win(code).unwrap();
                assert_eq!(from_win(scan, ext), Some(code));
            }
        }
    }

    #[test]
    fn common_keys() {
        assert_eq!(from_mac(0x08), Some(KeyCode::C));
        assert_eq!(from_mac(0x37), Some(KeyCode::LEFT_META));
        assert_eq!(to_win(KeyCode::LEFT_META), Some((0x5B, true)));
        assert_eq!(to_win(KeyCode::A), Some((0x1E, false)));
        assert_eq!(from_win(0x4B, true), Some(KeyCode::LEFT));
        // 不带扩展标记的 0x4B 是小键盘 4
        assert_eq!(from_win(0x4B, false), Some(KeyCode(0x5C)));
    }
}
